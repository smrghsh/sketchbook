// Assemble sketches.js from each sketch folder's meta.json.
// Usage: node tools/manifest.js [--order order.txt]
// order.txt = one slug per line (gallery order); unlisted slugs append
// alphabetically at the end.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const dir = path.join(ROOT, 'sketches');
const metas = [];
for (const slug of fs.readdirSync(dir)) {
  const p = path.join(dir, slug, 'meta.json');
  if (!fs.existsSync(p)) continue;
  const m = JSON.parse(fs.readFileSync(p, 'utf8'));
  m.slug = m.slug || slug;
  if (m.hidden) continue; // toggled via tools/admin.js
  metas.push(m);
}

let order = [];
const oi = process.argv.indexOf('--order');
if (oi !== -1) {
  order = fs
    .readFileSync(process.argv[oi + 1], 'utf8')
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}
metas.sort((a, b) => {
  const ia = order.indexOf(a.slug);
  const ib = order.indexOf(b.slug);
  if (ia !== -1 && ib !== -1) return ia - ib;
  if (ia !== -1) return -1;
  if (ib !== -1) return 1;
  return a.slug.localeCompare(b.slug);
});

const entries = metas.map((m) => ({
  slug: m.slug,
  title: m.title || m.slug,
  library: m.library || '',
  thumbDelay: m.thumbDelay || 4000,
}));

const out =
  '// sketchbook manifest — generated by tools/manifest.js from each\n' +
  '// sketch folder\'s meta.json. Edit order via tools/order.txt.\n\n' +
  'window.SKETCHES = ' +
  JSON.stringify(entries, null, 2) +
  ';\n';

fs.writeFileSync(path.join(ROOT, 'sketches.js'), out);
console.log(`${entries.length} sketches → sketches.js`);
entries.forEach((e) => console.log('  ' + e.slug));
